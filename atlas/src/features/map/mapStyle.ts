/**
 * The four basemaps Meridian can draw, all keyless.
 *
 *  - **`hybrid`** (the default) — satellite imagery with roads, borders and place
 *    names drawn on top. The generalist: it reads the same in Bavaria, Bengal or
 *    the middle of an ocean, needs no local knowledge to interpret, and shows the
 *    actual ground you journaled on rather than a cartographer's abstraction of it.
 *  - **`satellite`** — the same imagery with nothing over it.
 *  - **`parchment`** — Meridian's own vector cartography, coloured from the app's
 *    Cartographer's Parchment palette so the map reads as part of the app rather
 *    than a window onto someone else's website. Follows light/dark.
 *  - **`osm`** — plain OpenStreetMap raster tiles. The most forgiving option
 *    offline and on a weak device, and the automatic fallback.
 *
 * **Where the pixels come from.** Vector tiles (parchment, and the label overlay
 * in hybrid) come from **OpenFreeMap** (https://openfreemap.org) — OpenStreetMap
 * data in the OpenMapTiles schema, no API key, no account, no quota. Imagery comes
 * from **Esri's World Imagery** service, likewise keyless. That constraint is not
 * incidental: Meridian has no signup and holds no secrets, so anything needing a
 * token (Google's tiles among them — their terms also forbid raw tile access
 * outside their own APIs) was never an option.
 *
 * Two honest limitations:
 *
 *  1. **Labels use Noto Sans, not the app's Merriweather.** MapLibre renders text
 *     from pre-generated glyph atlases (`.pbf`), not from browser webfonts, so a
 *     font is only usable if someone serves its glyphs. OpenFreeMap serves the Noto
 *     stacks. Noto Sans has the side benefit of full Bengali coverage, which the
 *     app needs anyway.
 *  2. **Vector tiles need the network on first view.** Raster tiles — OSM *and*
 *     imagery — are cached by the service worker (see `vite.config.ts`), and the
 *     offline region download stores OSM raster tiles. So `'osm'` remains a
 *     first-class choice, not a legacy fallback: it is the most robust option
 *     offline. The map falls back to it automatically if a vector source fails,
 *     and hybrid degrades to plain `satellite` if only its labels fail.
 *
 * Every style is generated by a pure function so it can be unit-tested, and so the
 * dark parchment variant is genuinely the same style with a different palette
 * rather than a second copy that drifts.
 */
import type { StyleSpecification } from 'maplibre-gl';
import type { MapStyleId } from '../../store/settings';

const OPENFREEMAP_TILES = 'https://tiles.openfreemap.org/planet';
const OPENFREEMAP_GLYPHS = 'https://tiles.openfreemap.org/fonts/{fontstack}/{range}.pbf';
const OSM_RASTER = 'https://tile.openstreetmap.org/{z}/{x}/{y}.png';
/** Esri World Imagery. Note the tile path is `{z}/{y}/{x}` — row before column. */
const ESRI_IMAGERY =
  'https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}';

const ATTRIBUTION = '&copy; OpenStreetMap contributors';
const IMAGERY_ATTRIBUTION = 'Imagery &copy; Esri, Maxar, Earthstar Geographics';

/**
 * Deepest zoom the imagery service has tiles for. Declared on the source so
 * MapLibre over-zooms the z19 tile instead of requesting z20+ and collecting a
 * stream of 404s (which would look identical to a dead network).
 */
const IMAGERY_MAX_ZOOM = 19;

/** The colours any label layer needs, whatever it is drawn over. */
interface LabelColours {
  label: string;
  labelHalo: string;
  waterLabel: string;
}

/** Every colour the vector style uses, for one theme. */
interface Palette extends LabelColours {
  /** Bare ground — the map's equivalent of the app's parchment. */
  land: string;
  water: string;
  waterLine: string;
  /** Woods, parks, grass. */
  green: string;
  /** Sand, beaches, bare rock. */
  sand: string;
  /** Built-up area wash, under the individual buildings. */
  urban: string;
  building: string;
  buildingOutline: string;
  /** Motorways and trunk roads — the app's accent, so the network reads warm. */
  majorRoad: string;
  majorRoadCasing: string;
  minorRoad: string;
  minorRoadCasing: string;
  path: string;
  rail: string;
  boundary: string;
}

