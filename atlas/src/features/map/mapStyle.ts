/**
 * The style to hand MapLibre, for the user's chosen basemap and the current theme.
 * `dark` comes from the resolved theme (system-following already applied), not the
 * raw setting, and only the parchment style uses it.
 *
 * An unrecognised id resolves to the default basemap rather than throwing — a
 * settings blob from a future (or corrupted) version still gets a map.
 */
export function mapStyleFor(style: MapStyleId, dark: boolean): StyleSpecification {
  switch (style) {
    case 'parchment':
      return parchmentStyle(dark);
    case 'osm':
      return rasterStyle();
    case 'satellite':
      return satelliteStyle();
    case 'hybrid':
    default:
      return hybridStyle();
  }
}

/** Is the dark theme currently applied? Read from the `<html>` class that
 *  `theme.ts` toggles, so it reflects `system` too. */
export function isDarkTheme(): boolean {
  return typeof document !== 'undefined' && document.documentElement.classList.contains('dark');
}

/**
 * What to draw instead when a style's VECTOR source can't be reached (offline, or
 * the tile host is down). Hybrid keeps its imagery and simply loses its labels;
 * anything else falls all the way back to raster OSM, which the service worker and
 * the offline region download both cache.
 */
export function vectorFallbackFor(style: MapStyleId): MapStyleId {
  return style === 'hybrid' ? 'satellite' : 'osm';
}

